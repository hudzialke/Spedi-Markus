def stroke_icon(name: str, *, color: str = "#101820", size: int = 22) -> QIcon:
    inner = PATHS[name]
    raw = (
        '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" '
        'viewBox="0 0 24 24" fill="none" stroke="'
        f'{color}" stroke-width="2" stroke-linecap="round" '
        f'stroke-linejoin="round">{inner}</svg>'
    )
    renderer = QSvgRenderer(QByteArray(raw.encode("utf-8")))
    pix = QPixmap(size, size)
    pix.fill(Qt.GlobalColor.transparent)
    painter = QPainter(pix)
    renderer.render(painter, QRectF(0, 0, size, size))
    painter.end()
    return QIcon(pix)


def tool_button(
    tooltip: str,
    name: str,
    *,
    kind: str = "ghost",
    label: str = "",
) -> QToolButton:
    btn = QToolButton()
    color = "#ffffff" if kind in {"primary", "wa", "mail"} else "#101820"
    btn.setIcon(stroke_icon(name, color=color))
    btn.setIconSize(QSize(22, 22))
    btn.setToolTip(tooltip)
    btn.setAutoRaise(False)
    btn.setCursor(Qt.CursorShape.PointingHandCursor)
    if label:
        btn.setText(label)
        btn.setToolButtonStyle(Qt.ToolButtonStyle.ToolButtonTextBesideIcon)
        btn.setFixedHeight(42)
        btn.setMinimumWidth(88)
    else:
        btn.setFixedSize(42, 42)
        btn.setToolButtonStyle(Qt.ToolButtonStyle.ToolButtonIconOnly)
    if kind == "primary":
        btn.setObjectName("PrimaryButton")
    elif kind == "wa":
        btn.setObjectName("WaButton")
    elif kind == "mail":
        btn.setObjectName("MailButton")
    else:
        btn.setObjectName("GhostButton")
    return btn


def set_tool_icon(btn: QToolButton, name: str, *, kind: str = "ghost") -> None:
    color = "#ffffff" if kind in {"primary", "wa", "mail"} else "#101820"
    btn.setIcon(stroke_icon(name, color=color))
